// Helpers
export function findRomSchedule(scheduleInfoAddr) {
  if (!window.ALL_SCHEDULES_ROM || !scheduleInfoAddr) return null;
  return window.ALL_SCHEDULES_ROM.find(s => s.scheduleInfoAddr === scheduleInfoAddr) || null;
}
export function fomtTimeToMinutes(time) { return 360 + time; }
export function fomtFacingToDir(facing) {
  return ['down','left','up','right'][facing] || 'down';
}
export function buildGameScheduleFromRom(romSchedule, home) {
  if (!romSchedule || !romSchedule.schedules) return null;
  const sched = romSchedule.schedules.find(s => s !== null) || romSchedule.schedules[1];
  if (!sched || !sched.entries) return null;
  return sched.entries.filter(e => e.path).map(e => ({
    minutes: fomtTimeToMinutes(e.time),
    x: (((e.path.x_start >> 3) % 40 + 40) % 40) * 32,
    y: (((e.path.y_start >> 3) % 30 + 30) % 30) * 32,
    dir: fomtFacingToDir(e.path.facing),
    teleport: e.path.pointType === 1,
    location: e.path.location,
  }));
}
