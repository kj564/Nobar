// ===== fomt 1:1 Bachelorette system (bachelorette.hh, bachelorette.cc) =====
// Bachelorette extends Npc (bachelorette.hh:8). Only NPCs flagged isBachelorette=true
// (currently Maya) receive these mechanics. Love points: 0..65535 (16-bit).
// Player events: 0..6 (3-bit, cap 6). Rival events: 0..5 (3-bit, cap 5).
// Days since player/rival event: 0..7 (3-bit, cap 7).
//
// Constants used by bachDayUpdate (bachelorette.cc:95-123 EXACT port):
//   +200 love if spoken today          (line 98)
//   -200 love if ignored AND arg_01<10 (line 102-103, early game)
//   -1000 love @10% chance if all 6 player events seen AND ignored 5+ days (line 107-110)
//   -100 love flat if decayLove AND events incomplete (line 113-115)
//   days_since_player_event++ cap 7    (line 118-119)
//   days_since_rival_event++ cap 7     (line 121-122)
export const BACH_LOVE_MAX = 0xFFFF;       // 65535 — bachelorette.hh:26 love:16
export const BACH_PLAYER_EVENT_CAP = 6;     // bachelorette.cc:71 player_events<6
export const BACH_RIVAL_EVENT_CAP  = 5;     // bachelorette.cc:80 rival_events<5
export const BACH_DAYS_SINCE_CAP   = 7;     // bachelorette.cc:118,121 <7
export const BACH_SPOKEN_BONUS     = 200;   // bachelorette.cc:98 AddLove(200)
export const BACH_IGNORED_EARLY    = 200;   // bachelorette.cc:103 SubtractLove(200) — early game
export const BACH_RIVAL_OVERTAKE   = 1000; // bachelorette.cc:110 SubtractLove(1000) @10%
export const BACH_DECAY_FLAT       = 100;  // bachelorette.cc:114 SubtractLove(100) — flat
export const BACH_GIFT_LOVED_BONUS = 500;   // loved gift bonus (fomt gift bonus proxy)
export const BACH_GIFT_LIKED_BONUS = 300;   // liked gift bonus (fomt gift bonus proxy)
export const BACH_PROPOSE_LOVE_THRESHOLD = 60000;  // ~9.2 hearts — proposal unlock threshold
export const BACH_GIFT_MARRIAGE_FEATHER_PRICE = 1000;  // Blue Feather price (Carpenter)

// AddLove(amount) — bachelorette.cc:46-57 EXACT port: clamps total to [0, 0xFFFF]
export function bachAddLove(npc, amount) {
  if (!npc || !npc.isBachelorette) return;
  let total = (npc.love || 0) + amount;
  if (total < 0) total = 0;
  else if (total > BACH_LOVE_MAX) total = BACH_LOVE_MAX;
  npc.love = total;
}
// SubtractLove(amount) — bachelorette.cc:59-62: AddLove(-amount)
export function bachSubtractLove(npc, amount) { bachAddLove(npc, -amount); }

// SetLove(amount) — bachelorette.cc:64-67: direct assignment (no clamp)
export function bachSetLove(npc, amount) {
  if (!npc || !npc.isBachelorette) return;
  npc.love = amount;
}

// PlayerEventUpdate() — bachelorette.cc:69-76: if player_events<6, ++, reset days_since
export function bachPlayerEventUpdate(npc) {
  if (!npc || !npc.isBachelorette) return;
  if (npc.playerEvents < BACH_PLAYER_EVENT_CAP) {
    npc.playerEvents++;
    npc.daysSincePlayerEvent = 0;
  }
}
// RivalEventUpdate() — bachelorette.cc:78-85: if rival_events<5, ++, reset days_since
export function bachRivalEventUpdate(npc) {
  if (!npc || !npc.isBachelorette) return;
  if (npc.rivalEvents < BACH_RIVAL_EVENT_CAP) {
    npc.rivalEvents++;
    npc.daysSinceRivalEvent = 0;
  }
}
// method_0809E550() — bachelorette.cc:87-93: if unk_17_4<5, ++
export function bachMethod0809E550(npc) {
  if (!npc || !npc.isBachelorette) return;
  if (npc.unk_17_4 < 5) npc.unk_17_4++;
}

// DayUpdate(decay_love, arg_01, wasSpokenToday) — bachelorette.cc:95-123 EXACT port.
// decay_love: whether rival is active (typically after year 1: year >= 1).
// arg_01: year counter; arg_01 < 10 = early game (gentler -200 decay only).
// wasSpokenToday: pre-Npc::DayUpdate spoken_today flag (captured BEFORE the npc loop
//   resets it). fomt calls Npc::DayUpdate(arg_01) at line 100 INSIDE Bachelorette::DayUpdate,
//   which resets spoken_today. The +200 bonus at line 98 happens BEFORE that reset, so we
//   need the pre-reset value. The -200 penalty at line 102-103 reads
//   GetDaysSinceLastSpoken() AFTER the reset — i.e. days_since_last_spoken reflects
//   post-update state (0 if spoken, incremented if ignored).
export function bachDayUpdate(npc, decayLove, arg01, wasSpokenToday) {
  if (!npc || !npc.isBachelorette) return;
  // bachelorette.cc:97-98: spoken today → +200 love
  if (wasSpokenToday) bachAddLove(npc, BACH_SPOKEN_BONUS);
  // (Npc::DayUpdate is invoked separately in advanceDay — skip line 100)

  // bachelorette.cc:102-103: ignored + early game → -200 love
  // (days_since_last_spoken was incremented by Npc::DayUpdate; >0 means ignored today)
  if ((npc.days_since_last_spoken || 0) !== 0 && arg01 < 10) {
    bachSubtractLove(npc, BACH_IGNORED_EARLY);
  }

  // bachelorette.cc:105-116: decay_love branch
  if (decayLove) {
    if (npc.playerEvents > 5) {
      // bachelorette.cc:107-110: all 6 player events seen + neglected 5+ days
      // → 10% chance (rand()%100<10) to lose 1000 love (rival overtaking)
      if ((npc.days_since_last_spoken || 0) > 4 && Math.floor(Math.random() * 100) < 10) {
        bachSubtractLove(npc, BACH_RIVAL_OVERTAKE);
      }
    } else {
      // bachelorette.cc:113-115: events incomplete → flat -100 love/day
      bachSubtractLove(npc, BACH_DECAY_FLAT);
    }
  }

  // bachelorette.cc:118-119: days_since_player_event++ cap 7
  if ((npc.daysSincePlayerEvent || 0) < BACH_DAYS_SINCE_CAP) npc.daysSincePlayerEvent++;
  // bachelorette.cc:121-122: days_since_rival_event++ cap 7
  if ((npc.daysSinceRivalEvent || 0) < BACH_DAYS_SINCE_CAP) npc.daysSinceRivalEvent++;

  // Marriage proposal toast: if love crosses threshold and player owns Blue Feather.
  // Fires ONCE per session per bachelorette (tracked via _bachProposeToastShown flag).
  // Uses window.toast (set by index.html) to avoid a circular import.
  if ((npc.love || 0) >= BACH_PROPOSE_LOVE_THRESHOLD && player.blueFeather && !npc._bachProposeToastShown) {
    npc._bachProposeToastShown = true;
    if (typeof window.toast === 'function') {
      window.toast(`💍 Cinta ${npc.name} sudah 9 hati! Pakai Blue Feather (E di dekatnya) untuk melamar.`, 'gold');
    }
  }
}

// Love → hearts (65535 max → 10 hearts; ~6553.5 per heart = floor(love/6554))
export function bachLoveHearts(npc) {
  if (!npc || !npc.isBachelorette) return 0;
  return Math.floor((npc.love || 0) / 6554);
}
